package com.hsbc.cmb.hk.dbb.automation.framework.web.page.codegen.codegen.binding;

import com.hsbc.cmb.hk.dbb.automation.framework.web.page.codegen.codegen.binding.FeatureGlueGenerator.BindingStep;
import com.hsbc.cmb.hk.dbb.automation.framework.web.page.codegen.codegen.binding.FeatureGlueGenerator.FeatureGluePlan;
import com.hsbc.cmb.hk.dbb.automation.framework.web.page.codegen.codegen.binding.FeatureGlueGenerator.FeatureGlueResult;
import com.hsbc.cmb.hk.dbb.automation.framework.web.page.codegen.codegen.binding.FeatureGlueGenerator.ParamType;
import com.hsbc.cmb.hk.dbb.automation.framework.web.page.codegen.codegen.binding.FeatureGlueGenerator.Scenario;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;
import static org.junit.Assert.fail;

/**
 * {@link FeatureGlueGenerator} 的契约测试：Feature 字面值替换、Glue 注解表达式、委托调用、命名派生与错误拦截。
 */
public class FeatureGlueGeneratorTest {

    @Rule
    public TemporaryFolder tmp = new TemporaryFolder();

    /** 与 test-automation 的 role_element_login 同形的计划：Given 无参 + When 双 string + Then 无参。 */
    private static FeatureGluePlan roleElementPlan() {
        return FeatureGluePlan.named("Role element login")
                .gluePackage("com.example.glue")
                .steps("com.example.steps", "LoginSteps")
                .tags("regression", "login")
                .scenario(Scenario.named("Maker logs on")
                        .step(BindingStep.given("I open the login page").delegate("step1"))
                        .step(BindingStep.when("I log on as {string} with role {string}")
                                .param("username", ParamType.STRING)
                                .param("role", ParamType.STRING)
                                .args("alice", "maker")
                                .delegateForwarding("logon"))
                        .step(BindingStep.then("I should see the home page").delegate("step2")));
    }

    @Test
    public void feature_has_marker_tags_and_scenario_structure() {
        FeatureGlueResult r = FeatureGlueGenerator.generate(roleElementPlan());
        String f = r.featureContent;

        assertTrue("标记行", f.startsWith("# GENERATED BY CodegenInspector V3\n"));
        assertTrue("标签行", f.contains("\n@regression @login\n"));
        assertTrue("Feature 标题", f.contains("\nFeature: Role element login\n"));
        assertTrue("Scenario 缩进 2", f.contains("\n  Scenario: Maker logs on\n"));
        assertTrue("Given 步骤缩进 4", f.contains("\n    Given I open the login page\n"));
        assertTrue("Then 步骤缩进 4", f.contains("\n    Then I should see the home page\n"));
        assertFalse("不生成 Gherkin 之外的 Java 残留", f.contains("@Given"));
    }

    @Test
    public void feature_string_literals_are_quoted_in_place() {
        FeatureGlueResult r = FeatureGlueGenerator.generate(roleElementPlan());
        assertTrue("string 字面值带引号且原位替换",
                r.featureContent.contains("\n    When I log on as \"alice\" with role \"maker\"\n"));
    }

    @Test
    public void numeric_literal_is_not_quoted_and_signature_uses_int() {
        FeatureGluePlan plan = FeatureGluePlan.named("Transfer")
                .gluePackage("com.example.glue")
                .steps("com.example.steps", "TransferSteps")
                .scenario(Scenario.named("Transfer to payee")
                        .step(BindingStep.when("I transfer {int} HKD to account {string}")
                                .param("amount", ParamType.INT)
                                .param("account", ParamType.STRING)
                                .args("1000", "123456")
                                .delegateForwarding("transfer")));

        FeatureGlueResult r = FeatureGlueGenerator.generate(plan);
        assertTrue("int 字面值不带引号",
                r.featureContent.contains("\n    When I transfer 1000 HKD to account \"123456\"\n"));
        assertTrue("int 参数用 int", r.glueContent.contains(
                "public void i_transfer_hkd_to_account(int amount, String account) {"));
        assertTrue("透传参数", r.glueContent.contains("steps.transfer(amount, account);"));
    }

    @Test
    public void glue_annotation_keeps_cucumber_expression_verbatim() {
        FeatureGlueResult r = FeatureGlueGenerator.generate(roleElementPlan());
        assertTrue("注解保留占位符（不是字面值）",
                r.glueContent.contains("@When(\"I log on as {string} with role {string}\")"));
        assertTrue("注解保留 Given 短语",
                r.glueContent.contains("@Given(\"I open the login page\")"));
    }

    @Test
    public void glue_body_only_delegates_to_steps() {
        FeatureGlueResult r = FeatureGlueGenerator.generate(roleElementPlan());
        String g = r.glueContent;

        assertTrue("字段初始化 Steps", g.contains("private final LoginSteps steps = new LoginSteps();"));
        assertTrue("Given 委托录制步骤", g.contains("public void i_open_the_login_page() {\n        steps.step1();\n    }"));
        assertTrue("When 委托业务方法", g.contains(
                "public void i_log_on_as_with_role(String username, String role) {\n"
                        + "        steps.logon(username, role);\n    }"));
        assertFalse("不含定位器", g.contains("Playwright") || g.contains("locator("));
    }

    @Test
    public void no_arg_delegate_absorbs_phrase_params_with_comment() {
        FeatureGluePlan plan = FeatureGluePlan.named("Login via recorded step")
                .gluePackage("com.example.glue")
                .steps("com.example.steps", "LoginSteps")
                .scenario(Scenario.named("Recorded logon")
                        .step(BindingStep.when("I log on as {string}")
                                .param("username", ParamType.STRING)
                                .args("alice")
                                .delegate("step3")));

        FeatureGlueResult r = FeatureGlueGenerator.generate(plan);
        assertTrue("参数被吸收时给出注释", r.glueContent.contains("// 录制步骤无参：短语参数由 Steps 内部消化（username）"));
        assertTrue("委托无参方法", r.glueContent.contains("steps.step3();"));
        assertFalse("不把参数传给无参方法", r.glueContent.contains("step3(username)"));
    }

    @Test
    public void imports_only_used_keywords_and_steps_class() {
        FeatureGlueResult r = FeatureGlueGenerator.generate(roleElementPlan());
        assertTrue(r.glueContent.contains("import io.cucumber.java.en.Given;\n"));
        assertTrue(r.glueContent.contains("import io.cucumber.java.en.When;\n"));
        assertTrue(r.glueContent.contains("import io.cucumber.java.en.Then;\n"));
        assertFalse("未用 And/But 不引入", r.glueContent.contains("import io.cucumber.java.en.And;"));
        assertTrue(r.glueContent.contains("import com.example.steps.LoginSteps;\n"));
    }

    @Test
    public void same_package_steps_needs_no_import() {
        FeatureGluePlan plan = FeatureGluePlan.named("Same package")
                .gluePackage("com.example.pages")
                .steps("com.example.pages", "HomeSteps")
                .scenario(Scenario.named("Open home")
                        .step(BindingStep.given("I open the home page").delegate("step1")));

        FeatureGlueResult r = FeatureGlueGenerator.generate(plan);
        assertFalse("同包不 import", r.glueContent.contains("import com.example.pages.HomeSteps;"));
    }

    @Test
    public void names_are_derived_from_feature_name() {
        FeatureGlueResult r = FeatureGlueGenerator.generate(roleElementPlan());
        assertEquals("role_element_login.feature", r.featureFileName);
        assertEquals("RoleElementLoginGlue.java", r.glueFileName);
        assertTrue(r.glueContent.contains("public class RoleElementLoginGlue {"));
    }

    @Test
    public void explicit_names_override_derivation() {
        FeatureGluePlan plan = roleElementPlan()
                .featureFileName("custom.feature")
                .glueClass("CustomGlue");
        FeatureGlueResult r = FeatureGlueGenerator.generate(plan);
        assertEquals("custom.feature", r.featureFileName);
        assertEquals("CustomGlue.java", r.glueFileName);
        assertTrue(r.glueContent.contains("public class CustomGlue {"));
    }

    @Test
    public void placeholder_and_literal_count_mismatch_is_rejected() {
        FeatureGluePlan plan = FeatureGluePlan.named("Mismatch")
                .steps("com.example.steps", "LoginSteps")
                .scenario(Scenario.named("Broken")
                        .step(BindingStep.when("I log on as {string}")
                                .param("username", ParamType.STRING)
                                .args("alice", "extra")
                                .delegateForwarding("logon")));

        assertRejected(plan, "占位符");
    }

    @Test
    public void declared_type_must_match_placeholder_type() {
        FeatureGluePlan plan = FeatureGluePlan.named("Type mismatch")
                .steps("com.example.steps", "LoginSteps")
                .scenario(Scenario.named("Broken")
                        .step(BindingStep.when("I transfer {int} HKD")
                                .param("amount", ParamType.STRING)
                                .args("1000")
                                .delegateForwarding("transfer")));

        assertRejected(plan, "占位符类型");
    }

    @Test
    public void invalid_numeric_literal_is_rejected() {
        FeatureGluePlan plan = FeatureGluePlan.named("Bad number")
                .steps("com.example.steps", "LoginSteps")
                .scenario(Scenario.named("Broken")
                        .step(BindingStep.when("I transfer {int} HKD")
                                .param("amount", ParamType.INT)
                                .args("abc")
                                .delegateForwarding("transfer")));

        assertRejected(plan, "不是合法的 {int}");
    }

    @Test
    public void plan_without_steps_class_is_rejected() {
        FeatureGluePlan plan = FeatureGluePlan.named("No steps")
                .scenario(Scenario.named("Nothing").step(BindingStep.given("I open the page")));

        assertRejected(plan, "stepsClassName");
    }

    @Test
    public void duplicate_phrases_get_unique_method_names() {
        FeatureGluePlan plan = FeatureGluePlan.named("Repeated")
                .steps("com.example.steps", "LoginSteps")
                .scenario(Scenario.named("Twice")
                        .step(BindingStep.given("I open the login page").delegate("step1"))
                        .step(BindingStep.given("I open the login page").delegate("step1")));

        FeatureGlueResult r = FeatureGlueGenerator.generate(plan);
        assertTrue(r.glueContent.contains("public void i_open_the_login_page() {"));
        assertTrue("重名方法加序号", r.glueContent.contains("public void i_open_the_login_page_2() {"));
    }

    @Test
    public void writeTo_persists_both_artifacts() throws Exception {
        FeatureGlueResult r = FeatureGlueGenerator.generate(roleElementPlan());
        Path featureDir = tmp.newFolder("features").toPath();
        Path glueDir = tmp.newFolder("glue").toPath();

        r.writeTo(featureDir, glueDir);

        Path feature = featureDir.resolve("role_element_login.feature");
        Path glue = glueDir.resolve("RoleElementLoginGlue.java");
        assertTrue(Files.exists(feature));
        assertTrue(Files.exists(glue));
        assertEquals(r.featureContent, Files.readString(feature, StandardCharsets.UTF_8));
        assertEquals(r.glueContent, Files.readString(glue, StandardCharsets.UTF_8));
    }

    private static void assertRejected(FeatureGluePlan plan, String expectedFragment) {
        try {
            FeatureGlueGenerator.generate(plan);
            fail("应当拒绝非法计划");
        } catch (IllegalArgumentException e) {
            assertTrue("异常信息应包含 [" + expectedFragment + "]，实际: " + e.getMessage(),
                    e.getMessage().contains(expectedFragment));
        }
    }
}
