package com.hsbc.cmb.hk.dbb.automation.framework.web.page.codegen.codegen;

import com.hsbc.cmb.hk.dbb.automation.framework.web.page.codegen.model.CodegenEntry;
import com.hsbc.cmb.hk.dbb.automation.framework.web.utils.NLSUtils;
import org.junit.Assert;
import org.junit.Test;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.List;
import java.util.Map;

/**
 * Assert 类（Tab3）产物契约：与 Step 同构（<b>一次 Start→Pause 一个 {@code assertN} 方法</b>）、
 * hamcrest 风格、失败时显示 expected/actual 文本差异、按 role 选文本/勾选态/可见性。
 */
public class AssertClassGeneratorTest {

    private static final CodegenTarget TARGET =
            CodegenTarget.of("com.example.pages", "https://host/portalserver/login");

    private static CodegenEntry role(String role, String name, String css, int index) {
        return new CodegenEntry(role + "|" + name + "#" + index, role, name, "ROLE", 100, "role=" + role, css,
                null, index);
    }

    private static CodegenEntry roleWithKey(String role, String name, String css, int index, String nlsKey) {
        return new CodegenEntry(role + "|" + name + "#" + index, role, name, "ROLE", 100, "role=" + role, css,
                nlsKey, index);
    }

    private static Path writeBundle(String json) throws Exception {
        Path dir = Files.createTempDirectory("nls-assert");
        Path f = dir.resolve("x.nls.json");
        Files.writeString(f, json);
        return f;
    }

    private static int occurrences(String haystack, String needle) {
        int n = 0;
        int i = 0;
        while ((i = haystack.indexOf(needle, i)) >= 0) {
            n++;
            i += needle.length();
        }
        return n;
    }

    /** 单会话（= 一个 assert 方法）的 Assert 类：构造一个 session 单元再渲染。 */
    private static String assertClass(List<CodegenEntry> entries, String[] nlsFiles) {
        CodegenFieldPlanner.Plan plan = CodegenFieldPlanner.plan(entries, nlsFiles, Map.of());
        MultiPageCodegen.SessionUnit s = new MultiPageCodegen.SessionUnit(1, TARGET, List.of(TARGET), List.of(),
                List.of(new MultiPageCodegen.PageEntries(TARGET, entries, plan)));
        return AssertClassGenerator.generateSessions(TARGET, List.of(s), nlsFiles);
    }

    @Test
    public void rendersAssertClassSkeleton() {
        List<CodegenEntry> es = List.of(role("button", "Sign in", "#btn", 0));
        String out = assertClass(es, new String[]{});
        Assert.assertTrue(out.startsWith("// GENERATED BY CodegenInspector V3\n"));
        Assert.assertTrue(out.contains("package com.example.pages.assertions;"));
        Assert.assertTrue(out.contains("import com.example.pages.LoginPage;"));
        Assert.assertTrue(out.contains("import static org.hamcrest.MatcherAssert.assertThat;"));
        Assert.assertTrue(out.contains("import static org.hamcrest.Matchers.is;"));
        Assert.assertTrue(out.contains("public class LoginAssertions {"));
        // 会话模型：页面对象在该方法内实例化（局部变量），而非字段
        Assert.assertTrue(out.contains("LoginPage loginPage = PageObjectFactory.getPage(LoginPage.class);"));
        Assert.assertTrue(out.trim().endsWith("}"));
        Assert.assertFalse(out.contains("\r"));
    }

    /** 一次会话（Start→Pause）只产出一个 @Step 方法（assert1），与 Step 类的 step1 成对。 */
    @Test
    public void singleStepMethodPerSession() {
        List<CodegenEntry> es = Arrays.asList(
                role("button", "Sign in", "#btn", 0),
                role("textbox", "Username", "#u", 0));
        String step = StepClassGeneratorTest.stepClass(es);
        String out = assertClass(es, new String[]{});
        Assert.assertTrue(step.contains("public void step1() {"));
        Assert.assertTrue(out.contains("public void assert1() {"));
        Assert.assertEquals("只应有一个 @Step 方法（不是每个元素一个）", 1, occurrences(out, "@Step"));
    }

    /** 有 name 的普通元素断言文本；checkbox/radio 断言勾选态；无 name 退化为可见性。 */
    @Test
    public void assertionDerivesFromRole() {
        List<CodegenEntry> es = Arrays.asList(
                role("button", "Sign in", "#btn", 0),
                role("checkbox", "Remember me", "#r", 0),
                role("generic", "", "#wrap", 0));
        String out = assertClass(es, new String[]{});
        Assert.assertTrue(out.contains(
                "assertThat(loginPage.signIn.getText(), is(\"Sign in\"));"));
        Assert.assertTrue(out.contains(
                "assertThat(loginPage.rememberMe.isChecked(), is(true));"));
        Assert.assertTrue(out.contains(
                "assertThat(loginPage.wrap.isVisible(), is(true));"));
    }

    /** 方法体顺序 = 传入 entries 顺序（调用方已按真实操作序列排好）。 */
    @Test
    public void assertionOrderFollowsEntriesOrder() {
        List<CodegenEntry> es = Arrays.asList(
                role("button", "Second", "#b", 0),
                role("button", "First", "#a", 0));
        String out = assertClass(es, new String[]{});
        Assert.assertTrue(out.indexOf("loginPage.second") < out.indexOf("loginPage.first"));
    }

    /** 取值型角色（textbox 等）取 getValue() 而非 getText()。 */
    @Test
    public void valueRoleUsesGetValue() {
        List<CodegenEntry> es = List.of(role("textbox", "Username", "#u", 0));
        String out = assertClass(es, new String[]{});
        Assert.assertTrue(out.contains("assertThat(loginPage.username.getValue(), is(\"Username\"));"));
    }

    /** 断言产物使用 hamcrest，失败时由 JUnit 打印 expected 与 actual 文本差异。 */
    @Test
    public void usesHamcrestMatcher() {
        String out = assertClass(List.of(role("button", "OK", "#ok", 0)), new String[]{});
        Assert.assertTrue(out.contains("assertThat("));
        Assert.assertTrue(out.contains("is("));
        Assert.assertTrue(out.contains("org.hamcrest"));
    }

    /** 一组元素取 {@code get(0)} 单项做断言。 */
    @Test
    public void listFieldTargetsFirstItem() {
        List<CodegenEntry> es = Arrays.asList(
                role("listitem", "Item", "li.item", 0),
                role("listitem", "Item", "li.item", 1));
        String out = assertClass(es, new String[]{});
        Assert.assertTrue(out.contains("assertThat(loginPage.item.get(0).getText(), is(\"Item\"));"));
    }

    /** 三个 Tab 的字段名必须完全一致。 */
    @Test
    public void fieldNamesMatchPageAndStep() {
        List<CodegenEntry> es = Arrays.asList(
                role("button", "Sign in", "#btn", 0),
                role("textbox", "Username", "#u", 0));
        String page = PageClassGenerator.generate(TARGET, es, new String[]{});
        String step = StepClassGeneratorTest.stepClass(es);
        String asrt = assertClass(es, new String[]{});
        for (String f : new String[]{"signIn", "username"}) {
            Assert.assertTrue(page.contains("public PageElement " + f + ";"));
            Assert.assertTrue(step.contains("loginPage." + f + "."));
            Assert.assertTrue(asrt.contains("loginPage." + f + "."));
        }
    }

    /** 空拾取：只留可编译骨架，不产出空方法（与 Step 的 hasActions 语义一致）。 */
    @Test
    public void emptyPickStillRendersCompilableSkeleton() {
        String out = AssertClassGenerator.generateSessions(TARGET, List.of(), new String[]{});
        Assert.assertTrue(out.contains("public class LoginAssertions {"));
        Assert.assertTrue(out.trim().endsWith("}"));
        Assert.assertFalse(out.contains("assertThat("));
        Assert.assertFalse(out.contains("@Step"));
    }

    /** 有 NLS key 且可见文本精确相等 ⇒ 直接用已 bind 的 NLS 字段取文本、用 equalTo 断言（语言无关）。 */
    @Test
    public void nlsTextAssertionUsesEqualToWhenExact() throws Exception {
        Path f = writeBundle("{\"en\":{\"signin\":\"Sign in\"}}");
        NLSUtils.setLanguage("en");
        String out = assertClass(List.of(roleWithKey("button", "Sign in", "#btn", 0, "signin")),
                new String[]{f.toString()});
        Assert.assertTrue(out.contains("import com.hsbc.cmb.hk.dbb.automation.framework.web.utils.NLSUtils;"));
        Assert.assertTrue(out.contains("import static org.hamcrest.Matchers.equalTo;"));
        // bind 抽为一次性字段，不重复出现在每条断言
        Assert.assertTrue(out.contains("private static final NLSUtils.NlsBundle NLS = NLSUtils.bind("));
        // 不再生成冗余的 getKey(key) 私有透传方法
        Assert.assertFalse(out.contains("private static String getKey("));
        // 断言处直接走 NLS.visibleText，无重复的 NLSUtils.bind(...)
        Assert.assertTrue(out.contains("loginPage.signIn.getText(), equalTo(NLS.visibleText(\"signin\")));"));
        Assert.assertFalse("bind 不应出现在断言行", out.contains("equalTo(NLSUtils.bind("));
    }

    /** NLS 值含 HTML（可见文本是元素可见名的超集）⇒ 用 containsString 断言 NLS 值包含元素文本。 */
    @Test
    public void nlsTextAssertionUsesContainsStringWhenHtmlWrapsValue() throws Exception {
        Path f = writeBundle("{\"en\":{\"greet\":\"Hello <b>World</b>\"}}");
        NLSUtils.setLanguage("en");
        String out = assertClass(List.of(roleWithKey("heading", "World", "#h", 0, "greet")),
                new String[]{f.toString()});
        Assert.assertTrue(out.contains("import static org.hamcrest.Matchers.containsString;"));
        Assert.assertTrue(out.contains("private static final NLSUtils.NlsBundle NLS = NLSUtils.bind("));
        Assert.assertFalse(out.contains("private static String getKey("));
        Assert.assertTrue(out.contains("assertThat(NLS.visibleText(\"greet\"), containsString(loginPage.world.getText()));"));
        Assert.assertFalse("bind 不应出现在断言行", out.contains("containsString(NLSUtils.bind("));
    }

    /** RoleElement 的 checkbox 仍断言勾选态（isChecked），不受 NLS 文本断言影响。 */
    @Test
    public void checkboxStillAssertsIsCheckedWithNlsKeyPresent() throws Exception {
        Path f = writeBundle("{\"en\":{\"remember\":\"Remember me\"}}");
        NLSUtils.setLanguage("en");
        String out = assertClass(List.of(roleWithKey("checkbox", "Remember me", "#r", 0, "remember")),
                new String[]{f.toString()});
        Assert.assertTrue(out.contains("assertThat(loginPage.rememberMe.isChecked(), is(true));"));
    }
}
