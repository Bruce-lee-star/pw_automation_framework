package com.hsbc.cmb.hk.dbb.automation.framework.web.page.codegen.codegen;

import com.hsbc.cmb.hk.dbb.automation.framework.web.page.codegen.model.CodegenEntry;
import org.junit.Assert;
import org.junit.Test;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Map;

/**
 * Step 类（Tab2）产物契约：与 Page 同源的字段名、按 role 派生的动作动词、模板渲染，
 * 以及「一次 Start→Pause = 一个 {@code stepN} 方法」。
 *
 * <p>关键不变量：Step 里引用的字段名必须与 Page 类里生成的字段名<b>逐字相同</b>，
 * 否则三份产物拼不到一起（这是把命名收口到 {@link CodegenFieldPlanner} 的唯一目的）。
 */
public class StepClassGeneratorTest {

    private static final CodegenTarget TARGET =
            CodegenTarget.of("com.example.pages", "https://host/portalserver/login");

    private static CodegenEntry role(String role, String name, String css, int index) {
        return new CodegenEntry(role + "|" + name + "#" + index, role, name, "ROLE", 100, "role=" + role, css,
                null, index);
    }

    /** 单会话（= 一个 step 方法）的 Step 类：按录制值规划字段/动作后渲染。 */
    static String stepClass(List<CodegenEntry> entries, Map<String, String> fillValues) {
        CodegenFieldPlanner.Plan plan = CodegenFieldPlanner.plan(entries, new String[]{}, fillValues);
        List<MultiPageCodegen.SessionAction> actions = new ArrayList<>();
        for (CodegenEntry e : entries) {
            CodegenFieldSpec f = spec(plan, e);
            if (f == null) continue;
            boolean filled = fillValues != null && fillValues.get(e.sigKey) != null;
            String todo = ("fill".equals(f.verb) && !filled)
                    ? "replace the empty placeholder with the real input value" : "";
            actions.add(MultiPageCodegen.SessionAction.element(TARGET, f.fieldName, f.action, todo));
        }
        MultiPageCodegen.SessionUnit session = new MultiPageCodegen.SessionUnit(
                1, TARGET, List.of(TARGET), actions, List.of());
        return StepClassGenerator.generateSessions(TARGET, List.of(session));
    }

    static String stepClass(List<CodegenEntry> entries) {
        return stepClass(entries, Map.of());
    }

    private static CodegenFieldSpec spec(CodegenFieldPlanner.Plan plan, CodegenEntry e) {
        for (CodegenFieldSpec f : plan.fields) {
            if (f.entry == e) return f;
        }
        return null;
    }

    @Test
    public void rendersStepClassSkeleton() {
        String out = stepClass(List.of(role("button", "Sign in", "#btn", 0)));
        Assert.assertTrue(out.startsWith("// GENERATED BY CodegenInspector V3\n"));
        Assert.assertTrue(out.contains("package com.example.pages.steps;"));
        Assert.assertTrue(out.contains("import com.example.pages.LoginPage;"));
        Assert.assertTrue(out.contains(
                "import com.hsbc.cmb.hk.dbb.automation.framework.report.annotation.Step;"));
        Assert.assertTrue(out.contains(
                "import com.hsbc.cmb.hk.dbb.automation.framework.web.page.factory.PageObjectFactory;"));
        Assert.assertTrue(out.contains("public class LoginSteps {"));
        Assert.assertTrue("step 方法内应实例化页面类（局部变量）",
                out.contains("LoginPage loginPage = PageObjectFactory.getPage(LoginPage.class);"));
        Assert.assertTrue(out.trim().endsWith("}"));
        Assert.assertFalse(out.contains("\r"));
    }

    /** 一次会话一个 @Step；方法体按 role 派生动作：button→click、textbox→fill("")、checkbox→check()。 */
    @Test
    public void actionDerivesFromRole() {
        List<CodegenEntry> es = Arrays.asList(
                role("button", "Sign in", "#btn", 0),
                role("textbox", "Username", "#u", 0),
                role("checkbox", "Remember me", "#r", 0));
        String out = stepClass(es);
        // 一次 Start→Pause 只产出一个 @Step 方法：step1
        Assert.assertEquals("一次会话只生成一个 @Step 方法", 1, countOccurrences(out, "@Step"));
        Assert.assertTrue(out.contains("public void step1() {"));
        Assert.assertTrue(out.contains("loginPage.signIn.click();"));
        Assert.assertTrue(out.contains("loginPage.username.fill(\"\");"));
        Assert.assertTrue(out.contains("loginPage.rememberMe.check();"));
        // 占位值必须显式留 TODO，不能静默提交空值
        Assert.assertTrue(out.contains("TODO(review): replace the empty placeholder with the real input value"));
    }

    /** 一组元素（PageElementList）在 Step 里取 {@code get(0)} 单项，保证产物可编译。 */
    @Test
    public void listFieldTargetsFirstItem() {
        List<CodegenEntry> es = Arrays.asList(
                role("listitem", "Item", "li.item", 0),
                role("listitem", "Item", "li.item", 1));
        String out = stepClass(es);
        Assert.assertTrue(out.contains("loginPage.item.get(0).click();"));
        Assert.assertEquals("一组元素只生成一个步骤方法", 1, countOccurrences(out, "@Step"));
    }

    /** Step 引用的字段名必须与 Page 类生成的一致（同源规划的硬保证）。 */
    @Test
    public void fieldNamesMatchPageClass() {
        List<CodegenEntry> es = Arrays.asList(
                role("button", "Sign in", "#btn", 0),
                role("textbox", "Username", "#u", 0));
        String page = PageClassGenerator.generate(TARGET, es, new String[]{});
        String step = stepClass(es);
        Assert.assertTrue(page.contains("public PageElement signIn;"));
        Assert.assertTrue(page.contains("public PageElement username;"));
        Assert.assertTrue(step.contains("loginPage.signIn."));
        Assert.assertTrue(step.contains("loginPage.username."));
    }

    @Test
    public void emptyPickStillRendersCompilableSkeleton() {
        // 没有任何会话 ⇒ 只有可编译骨架，不产出空方法
        String out = StepClassGenerator.generateSessions(TARGET, List.of());
        Assert.assertTrue(out.contains("public class LoginSteps {"));
        Assert.assertTrue(out.trim().endsWith("}"));
        Assert.assertFalse(out.contains("@Step"));
    }

    /** 录制到输入值时，Step 类应回填真实 fill 值（不再留空占位 + TODO）。 */
    @Test
    public void fillsRecordedValueWhenAvailable() {
        List<CodegenEntry> es = Arrays.asList(
                role("textbox", "Username", "#u", 0),
                role("textbox", "Password", "#p", 0));
        Map<String, String> values = Map.of(
                "textbox|Username#0", "alice",
                "textbox|Password#0", "S3cret!");
        String out = stepClass(es, values);
        Assert.assertTrue(out.contains("loginPage.username.fill(\"alice\");"));
        Assert.assertTrue(out.contains("loginPage.password.fill(\"S3cret!\");"));
        Assert.assertFalse("已回填真实值不应再出现空占位 TODO",
                out.contains("replace the empty placeholder with the real input value"));
    }

    private static int countOccurrences(String s, String sub) {
        int c = 0, i = 0;
        while ((i = s.indexOf(sub, i)) >= 0) { c++; i += sub.length(); }
        return c;
    }
}
