    /**
     * 从一组已解析的 {@link RoleEntry} 生成完整可编译的 Page 类源码。
     * 这是核心方法：整页 tree、按需拾取、或外部来源都先转换为条目列表再调用本方法。
     *
     * @param entries       元素列表（role + name）
     * @param packageName   生成类的包名
     * @param pageClassName 生成类名
     * @param nlsFiles       类级 {@code @RoleFile} 路径
     * @return 完整 Java 类源码
     */
    public static String generate(List<RoleEntry> entries, String packageName,
                                  String pageClassName, String... nlsFiles) {
        // 【修复「没传 nls file 却生成 key= 定位」】只有确实会生成类级 @RoleFile（即传了 NLS 文件）时，
        // 才允许用 NLS key 定位；否则一律退化为可访问名(name)/文本定位，保证产物无需 NLS 表即可运行。
        boolean allowNlsKey = (nlsFiles != null && nlsFiles.length > 0);
        List<GeneratedField> specs = assignFields(entries, allowNlsKey);
        StringBuilder fields = new StringBuilder();
        boolean hasRole = false;          // 任意 @RoleElement 字段（角色或语义）
        boolean hasAriaRole = false;      // 角色策略字段（需 import AriaRole 常量）
        boolean hasElement = false;
        boolean hasList = false;          // 任意 PageElementList 列表字段（需 import PageElementList）
        for (GeneratedField s : specs) {
            RoleEntry e = s.entry;
            if (e.isRoleStrategy()) {
                hasRole = true;
                hasAriaRole = true;
            } else {
                switch (e.getStrategy()) {
                    case RolePickerConstants.STRATEGY_TEXT:
                    case RolePickerConstants.STRATEGY_ALT_TEXT:
                    case RolePickerConstants.STRATEGY_TITLE:
                    case RolePickerConstants.STRATEGY_PLACEHOLDER:
                    case RolePickerConstants.STRATEGY_TEST_ID:
                    case RolePickerConstants.STRATEGY_LABEL:
                        hasRole = true; break;   // 语义字段也归类于 @RoleElement
                    default:
                        hasElement = true; break;   // id / css 等纯 CSS/XPath
                }
            }
            // 标注元素归属空间（space）：iframe / shadow 嵌套位置。非默认 "main" 时写注释，
            // 便于阅读生成类时直观看出该元素位于哪个空间（与 step 内 frame 切换逻辑同源）。
            String space = s.entry.getSpace();
            List<String> framePath = s.entry.getFramePath();
            if (space != null && !"main".equals(space)) {
                fields.append("    // space: ").append(space).append("\n");
            }
            // 【明确"iframe 元素属于哪个控件"】当元素来自某个 iframe（framePath 非空）时，
            // 额外标注其归属的 iframe 控件层级，让使用者一眼知道该字段是「frameOne 里的 …」还是
            // 「frameTwo→frameOne 嵌套里的 …」，避免与主页元素混淆。
            if (framePath != null && !framePath.isEmpty()) {
                String frameReadable = framePath.stream()
                        .map(seg -> seg.replaceAll("^\\[|\\]$", ""))
                        .collect(Collectors.joining(" → "));
                fields.append("    // 控件: iframe [").append(frameReadable).append("]\n");
            }
            // 【列表字段】被标记为「一组元素」的拾取生成 {@code PageElementList} 字段（一个定位器表达整组，
            // 业务 {@code x.get(i)} 取单项，语义等价 page.pause 的 locator.nth(i)）；否则仍是单个 {@code PageElement}。
            if (e.isList()) {
                hasList = true;
                fields.append(s.annotation).append("\n    public PageElementList ").append(s.fieldName).append(";\n\n");
            } else {
                fields.append(s.annotation).append("\n    public PageElement ").append(s.fieldName).append(";\n\n");
            }
        }

        // 按需构建 import：只有存在对应字段类型时才引入，避免未使用的 import。
        StringBuilder imports = new StringBuilder();
        if (hasAriaRole) {
            imports.append("import com.microsoft.playwright.options.AriaRole;\n\n");
        }
        imports.append("import com.hsbc.cmb.hk.dbb.automation.framework.web.page.element.PageElement;\n");
        if (hasList) {
            imports.append("import com.hsbc.cmb.hk.dbb.automation.framework.web.page.element.PageElementList;\n");
        }
        if (hasElement) {
            imports.append("import com.hsbc.cmb.hk.dbb.automation.framework.web.page.element.Element;\n");
        }
        if (hasRole) {
            imports.append("import com.hsbc.cmb.hk.dbb.automation.framework.web.page.element.RoleElement;\n");
            imports.append("import com.hsbc.cmb.hk.dbb.automation.framework.web.page.element.RoleFile;\n");
        }
        imports.append("import com.hsbc.cmb.hk.dbb.automation.framework.web.page.base.AbstractManagedPage;\n");

        // 只有存在 @RoleElement 字段时才需要类级 @RoleFile（NLS 文件）。
        // 支持一页面对应多个 nls 文件：单文件生成 @RoleFile("x")，多文件生成 @RoleFile({"a","b"})。
        String classAnnotation = "";
        if (hasRole && nlsFiles != null && nlsFiles.length > 0) {
            if (nlsFiles.length == 1) {
                classAnnotation = "@RoleFile(\"" + escapeJava(nlsFiles[0]) + "\")\n";
            } else {
                StringBuilder sb = new StringBuilder("@RoleFile({");
                for (int i = 0; i < nlsFiles.length; i++) {
                    if (i > 0) sb.append(", ");
                    sb.append('"').append(escapeJava(nlsFiles[i])).append('"');
                }
                sb.append("})\n");
                classAnnotation = sb.toString();
            }
        }

        return "// " + GENERATED_MARKER + "\n"
                + "package " + packageName + ";\n\n"
                + imports + "\n"
                + classAnnotation
                + "public class " + pageClassName + " extends AbstractManagedPage {\n\n"
                //  F-15：生成内容包进标记块 —— 再生成时只替换块内，块外手写代码不被覆盖。
                + FIELDS_BLOCK_BEGIN + "\n"
                + fields
                + FIELDS_BLOCK_END + "\n"
                + "}\n";
    }

